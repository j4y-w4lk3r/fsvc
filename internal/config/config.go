// Package config loads and persists the fsvc configuration from
// ~/.config/fsvc/config.toml (or wherever XDG_CONFIG_HOME points).
//
// The schema deliberately keeps everything (Revolut endpoint, mTLS cert
// paths, OAuth credentials, both tokens) in one TOML file. Why not split
// "stable config" from "rotating tokens" into two files: every token
// refresh would still need to write SOMETHING to disk, the file write is
// already atomic via the rename pattern in Save, and a single canonical
// file is easier to ykw-encrypt + bbm-push as a unit. Trade-off: every
// `fsvc revolut auth` rewrites the whole file, but at ~500 bytes that's
// fine.
//
// Cred resolution cascade (per field, first non-empty wins):
//
//  1. CLI flags (passed via Globals.Overrides — not implemented in v0.1.0,
//     reserved for v0.1.x parity with bbm).
//  2. Process env vars (REVOLUT_*).
//  3. config.toml.
//
// Path expansion: any field ending in _path that starts with "~" is
// expanded relative to $HOME. Done at Load time so callers can pass
// resolved absolute paths to crypto/tls and friends without thinking
// about it.
package config

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/BurntSushi/toml"
)

// ErrNoConfig is returned by Load when the resolved config file path
// doesn't exist on disk. Callers can errors.Is it to render a helpful
// "run `fsvc init` first" walkthrough.
var ErrNoConfig = errors.New("no fsvc config found")

// Config is the on-disk schema. Field names map 1:1 to TOML keys via
// the `toml:"..."` tags so config.toml stays readable.
type Config struct {
	// Path of the file we Loaded from / will Save to. Not serialized;
	// set by Load so subsequent Save() calls know where to write.
	path string `toml:"-"`

	// [revolut] — the Revolut Business API client credentials and
	// mTLS material. See https://developer.revolut.com/docs/business
	Revolut RevolutConfig `toml:"revolut"`
}

// RevolutConfig is the Revolut Business API subsection.
type RevolutConfig struct {
	// BaseURL of the Revolut Business API. Defaults to the production
	// b2b endpoint; override for sandbox.
	BaseURL string `toml:"base_url"`

	// ClientID issued by Revolut after you upload your public cert in
	// the Revolut Business → Settings → APIs flow. Identifies your
	// integration for the JWT `sub` claim.
	ClientID string `toml:"client_id"`

	// ISS is the JWT issuer claim. Revolut requires this to match the
	// host portion of your registered redirect URI (e.g. "fsvc.local"
	// for redirect_uri "https://fsvc.local/callback").
	ISS string `toml:"iss"`

	// RedirectURI is the OAuth redirect_uri registered with Revolut
	// when you uploaded the cert. `fsvc revolut authorize` parses this
	// to know which port to listen on and which path to handle, AND
	// echoes it verbatim in the consent URL (Revolut requires byte-
	// for-byte match against what's registered).
	//
	// Default for a typical desktop setup: http://localhost:8080/callback
	RedirectURI string `toml:"redirect_uri"`

	// CertPath is the path to the client certificate (PEM) presented
	// to Revolut for mTLS. Generated by `fsvc cert`. ~ is expanded.
	CertPath string `toml:"cert_path"`

	// KeyPath is the path to the matching private key (PEM). MUST be
	// chmod 600. ~ is expanded.
	KeyPath string `toml:"key_path"`

	// AccessToken is the most recently issued access_token. Rotates
	// roughly every 40 minutes (Revolut's expires_in). `fsvc revolut
	// auth` refreshes this and writes the new value back via Save().
	AccessToken string `toml:"access_token,omitempty"`

	// AccessExpiresAt is the wall-clock time at which AccessToken
	// expires. If zero or in the past, callers should call
	// `fsvc revolut auth` before any API request.
	AccessExpiresAt time.Time `toml:"access_expires_at,omitempty"`

	// RefreshToken is the long-lived (90-day) refresh_token issued
	// from the initial OAuth consent flow. Used to mint new access
	// tokens. May ALSO rotate (Revolut occasionally issues a new
	// one); Save() writes the latest value back.
	RefreshToken string `toml:"refresh_token,omitempty"`
}

// Path returns the on-disk location this Config was loaded from
// (or where it would be saved if loaded with a custom path).
func (c *Config) Path() string { return c.path }

// New returns a fresh Config wired to write to `path` on Save(). Used
// by `fsvc init` to scaffold a config from CLI flags rather than
// loading an existing one. Callers fill in the fields they care about
// and call Save().
func New(path string) *Config {
	return &Config{path: path}
}

// DefaultPath returns the canonical fsvc config location:
// $XDG_CONFIG_HOME/fsvc/config.toml, defaulting to
// $HOME/.config/fsvc/config.toml when XDG_CONFIG_HOME is unset.
//
// Returns "" if HOME is also unset (extremely unusual; means the
// caller is running in a stripped environment).
func DefaultPath() string {
	if x := os.Getenv("XDG_CONFIG_HOME"); x != "" {
		return filepath.Join(x, "fsvc", "config.toml")
	}
	if h, err := os.UserHomeDir(); err == nil {
		return filepath.Join(h, ".config", "fsvc", "config.toml")
	}
	return ""
}

// Load reads the config from `path` (or DefaultPath() if empty),
// expands ~-paths in cert_path/key_path, and overlays REVOLUT_* env
// vars on top of file values. Returns ErrNoConfig when the file
// doesn't exist (so callers can hand the user a "run `fsvc init`"
// walkthrough rather than an opaque "no such file").
func Load(path string) (*Config, error) {
	if path == "" {
		path = DefaultPath()
	}
	if path == "" {
		return nil, errors.New("config: cannot resolve config path (HOME unset?)")
	}

	if _, err := os.Stat(path); err != nil {
		if os.IsNotExist(err) {
			return nil, fmt.Errorf("%w: %s", ErrNoConfig, path)
		}
		return nil, fmt.Errorf("config: stat %s: %w", path, err)
	}

	cfg := &Config{path: path}
	if _, err := toml.DecodeFile(path, cfg); err != nil {
		return nil, fmt.Errorf("config: parse %s: %w", path, err)
	}

	cfg.applyEnvOverrides()
	cfg.expandPaths()
	cfg.applyDefaults()
	return cfg, nil
}

// applyEnvOverrides lets REVOLUT_* env vars override file values. Same
// shape as the Python codebase used (REVOLUT_BASE_URL, REVOLUT_TOKEN,
// REVOLUT_REFRESH_TOKEN, etc.) so anyone with a stashed shell-export
// snippet from the legacy code can keep using it.
func (c *Config) applyEnvOverrides() {
	if v := os.Getenv("REVOLUT_BASE_URL"); v != "" {
		c.Revolut.BaseURL = v
	}
	if v := os.Getenv("REVOLUT_CLIENT_ID"); v != "" {
		c.Revolut.ClientID = v
	}
	if v := os.Getenv("REVOLUT_ISS"); v != "" {
		c.Revolut.ISS = v
	}
	if v := os.Getenv("REVOLUT_REDIRECT_URI"); v != "" {
		c.Revolut.RedirectURI = v
	}
	if v := os.Getenv("REVOLUT_CERT_PATH"); v != "" {
		c.Revolut.CertPath = v
	}
	if v := os.Getenv("REVOLUT_KEY_PATH"); v != "" {
		c.Revolut.KeyPath = v
	}
	if v := os.Getenv("REVOLUT_TOKEN"); v != "" {
		c.Revolut.AccessToken = v
	}
	if v := os.Getenv("REVOLUT_REFRESH_TOKEN"); v != "" {
		c.Revolut.RefreshToken = v
	}
}

// expandPaths rewrites cert_path / key_path leading "~" to $HOME so
// callers can pass them directly to tls.LoadX509KeyPair. Done at Load
// time, not per-call, because cert/key paths are stable for the
// session.
func (c *Config) expandPaths() {
	c.Revolut.CertPath = expandHome(c.Revolut.CertPath)
	c.Revolut.KeyPath = expandHome(c.Revolut.KeyPath)
}

// applyDefaults fills in sensible values for fields the user might
// reasonably omit. Only BaseURL has a meaningful default — everything
// else is per-account.
func (c *Config) applyDefaults() {
	if c.Revolut.BaseURL == "" {
		c.Revolut.BaseURL = "https://b2b.revolut.com/api/1.0"
	}
}

// Save writes the config back to disk atomically (write to .tmp +
// rename) with mode 0600. Used by `fsvc revolut auth` to persist the
// rotated access_token / refresh_token.
//
// The atomic-rename pattern matters here because Revolut's token-
// refresh response is what we're writing — losing it to a crash mid-
// write would mean the user has to re-do the OAuth consent flow.
func (c *Config) Save() error {
	if c.path == "" {
		return errors.New("config: Save called on a Config with no path")
	}
	if err := os.MkdirAll(filepath.Dir(c.path), 0o700); err != nil {
		return fmt.Errorf("config: mkdir %s: %w", filepath.Dir(c.path), err)
	}

	tmp := c.path + ".tmp"
	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o600)
	if err != nil {
		return fmt.Errorf("config: create %s: %w", tmp, err)
	}
	enc := toml.NewEncoder(f)
	enc.Indent = ""
	if err := enc.Encode(c); err != nil {
		f.Close()
		os.Remove(tmp)
		return fmt.Errorf("config: encode: %w", err)
	}
	if err := f.Close(); err != nil {
		os.Remove(tmp)
		return fmt.Errorf("config: close %s: %w", tmp, err)
	}
	if err := os.Rename(tmp, c.path); err != nil {
		return fmt.Errorf("config: rename %s -> %s: %w", tmp, c.path, err)
	}
	return nil
}

// Validate returns a list of human-readable problems with the config.
// Empty list = ready for API calls. Used by `fsvc revolut auth` and
// friends to fail fast with a useful error rather than a 401 from
// Revolut.
func (c *Config) Validate() []string {
	var problems []string
	r := &c.Revolut
	if r.BaseURL == "" {
		problems = append(problems, "revolut.base_url is empty")
	}
	if r.ClientID == "" {
		problems = append(problems, "revolut.client_id is empty (run `fsvc init` after uploading your public cert to Revolut Business → Settings → APIs)")
	}
	if r.ISS == "" {
		problems = append(problems, "revolut.iss is empty (must match your registered redirect_uri host)")
	}
	if r.CertPath == "" {
		problems = append(problems, "revolut.cert_path is empty (run `fsvc cert` to generate a keypair)")
	}
	if r.KeyPath == "" {
		problems = append(problems, "revolut.key_path is empty (run `fsvc cert` to generate a keypair)")
	}
	if r.CertPath != "" {
		if _, err := os.Stat(r.CertPath); err != nil {
			problems = append(problems, fmt.Sprintf("revolut.cert_path %s: %v", r.CertPath, err))
		}
	}
	if r.KeyPath != "" {
		if _, err := os.Stat(r.KeyPath); err != nil {
			problems = append(problems, fmt.Sprintf("revolut.key_path %s: %v", r.KeyPath, err))
		}
	}
	return problems
}

// expandHome handles only the leading "~/" form (NOT "~user/" — that
// requires resolving usernames via the os/user package and is
// out-of-scope; nobody puts cert paths under another user's home
// anyway).
func expandHome(p string) string {
	if p == "" || !strings.HasPrefix(p, "~") {
		return p
	}
	if p == "~" || strings.HasPrefix(p, "~/") {
		if h, err := os.UserHomeDir(); err == nil {
			return filepath.Join(h, strings.TrimPrefix(p, "~"))
		}
	}
	return p
}
